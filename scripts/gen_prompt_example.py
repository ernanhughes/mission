"""Generate a real copy-review-prompt artifact for the acceptance record."""

import subprocess
import tempfile
from pathlib import Path

from mission_control.activity_git.service import GitActivityService
from mission_control.config import RuntimeSettings
from mission_control.models import DiscoveryRoot
from mission_control.persistence.db import Database, now_iso
from mission_control.persistence.migrations import apply_migrations


def _git(repo: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(repo), *args],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=30, shell=False, check=False,
    )
    assert result.returncode == 0, result.stderr[:300]
    return (result.stdout or "").strip()


tmp = Path(tempfile.mkdtemp())
root = tmp / "projects"
repo = root / "demo"
repo.mkdir(parents=True, exist_ok=True)
_git(repo, "init")
_git(repo, "config", "user.name", "T")
_git(repo, "config", "user.email", "t@e.com")
_git(repo, "config", "commit.gpgsign", "false")
(repo / "calc.py").write_text("def add(a, b):\n    return a + b\n")
(repo / "AGENTS.md").write_text("# Agents\n- Run pytest before finishing.\n- Keep diffs scoped.\n")
(repo / "DESCRIPTION.md").write_text("# Demo\nA tiny calculator library.\n")
_git(repo, "add", "-A")
_git(repo, "commit", "-m", "feat: add calculator", "--no-gpg-sign")
(repo / "calc.py").write_text(
    "def add(a, b):\n    return a + b\n\ndef div(a, b):\n    return a / b\n"
)
(repo / "config.env").write_text("API_KEY=topsecret-value-123\n")
_git(repo, "add", "-A")
_git(repo, "commit", "-m", "feat: add division without zero guard", "--no-gpg-sign")

rt = RuntimeSettings(
    repo_root=Path(".").resolve(),
    data_dir=tmp / "data",
    config_dir=Path("config").resolve(),
    frontend_dist=tmp / "dist",
    book_root=tmp / "books",
    start_monitor=False,
    seed_defaults=False,
)
db = Database(rt)
apply_migrations(db)
with db.session() as session:
    session.add(DiscoveryRoot(path=str(root), enabled=True, added_at=now_iso(),
                              display_name="F", category="software", git_enabled=True))

svc = GitActivityService(db)
with db.session() as session:
    repos = svc._discover_all([str(root)], {**svc.get_config(session), "max_depth": 4,
                                            "max_repos_per_scan": 2000}, [])
    items = repos[0] if isinstance(repos, tuple) else repos
    for item in items:
        svc._sync_one_repo(item, {**svc.get_config(session), "recent_days": 30,
                                  "diff_max_bytes": 120000, "backfill_page": 500,
                                  "prompt_max_chars": 60000, "concurrency": 8})
    timeline, total, partial = svc.timeline(session, preset="30d", limit=10)
    target = next(item for item in timeline if "division" in item["subject"])
    package = svc.build_prompt(session, target["repo_id"], target["sha"], profile="code")

out = Path("docs/acceptance/mc-activity-01/review-prompt-example.md")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(
    "<!-- Generated by scripts/gen_prompt_example.py from a synthetic fixture repo. -->\n"
    "<!-- No model call was made. Secrets in the fixture diff are redacted below. -->\n\n"
    + package["markdown"],
    encoding="utf-8",
)
print("wrote", out, package["size_chars"], "chars;",
      "redactions:", package["redaction_count"], "truncated:", package["truncated"])
print("coverage:", package["coverage"])
assert "topsecret-value-123" not in package["markdown"], "secret leaked into prompt"
print("secret-leak check: OK")
