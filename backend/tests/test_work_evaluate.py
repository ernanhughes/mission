def _seed_episode(database, eid="ep:task:T1", sha="a1b2c3d4e5f60718293a4b5c6d7e8f9012345678"):
    from mission_control import models as orm

    with database.session() as session:
        session.add(orm.WoEpisode(id=eid, project_key="p", title="T1",
                                  kind="task", status="established"))
        session.add(orm.WoRequirement(id="rq1", episode_id=eid,
                                      text="Ship the thing", authority="explicit_user",
                                      mandatory=1, kind="functional", state="proposed"))
        session.add(orm.WoRequirement(id="rq2", episode_id=eid,
                                      text="Docs update", authority="suggested",
                                      mandatory=0, kind="functional", state="proposed"))
        session.add(orm.WoClaim(id="cl1", episode_id=eid, claimant="assistant",
                                text=f"Merged {sha} to main", scope="s",
                                source_ref="opencode:s1:3"))
        session.add(orm.WoClaim(id="cl2", episode_id=eid, claimant="assistant",
                                text="All 12 tests passed", scope="s",
                                source_ref="opencode:s1:5"))
        session.add(orm.WoEpisodeAssociation(
            id="as1", episode_id=eid, assoc_type="commit",
            target_ref=f"git-1:{sha}", method="explicit", confidence="explicit",
            reason="r", signals=[], recon_version=1, valid=1))
        # Explicit W3-style evidence binding for rq1 (resolvable).
        session.add(orm.WoEvidenceLink(
            id="ev1", requirement_id="rq1", evidence_kind="git_commit",
            evidence_ref=f"git-1:{sha}", source_digest="d",
            method="candidate", confidence="moderate"))
    return sha


def test_service_deterministic_episode(tmp_path, runtime) -> None:
    service, database = _eval_svc(tmp_path, runtime)
    _seed_episode(database)
    out = service.evaluate_episode("ep:task:T1", semantic=False)
    assert out["status"] == "completed"
    assert out["requirements_assessed"] == 2
    assert out["claims_verified"] == 2
    assert out["model_calls"] == 0
    reqs = {r["requirement_id"]: r["verdict"]
            for r in service.list_req_assessments("ep:task:T1")}
    # rq1: commit-linked but correctness unjudged -> reported; rq2 optional -> na.
    assert reqs["rq1"] == "satisfied_reported"
    assert reqs["rq2"] == "not_applicable"
    claims = {c["claim_id"]: c["verdict"]
              for c in service.list_claim_verifications("ep:task:T1")}
    assert claims["cl1"] == "verified_commit_exists"
    assert claims["cl2"] == "reported_only"
    ep = service.get_episode_assessment("ep:task:T1")
    assert ep["completion"]["verdict"] in ("partial", "unknown")
    assert ep["completion"]["verdict"] != "complete"  # reported is never complete
    findings = service.list_findings(episode_id="ep:task:T1")
    assert any(f["kind"] == "verification_gap" for f in findings)
    # Idempotent rerun adds no duplicate findings.
    service.evaluate_episode("ep:task:T1", semantic=False)
    assert len(service.list_findings(episode_id="ep:task:T1")) == len(findings)


