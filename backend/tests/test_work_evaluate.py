def test_claim_digest_dedupe_across_occurrences(tmp_path, runtime) -> None:
    # Review F5: same (text, scope, revision) verified once, reused after.
    from mission_control import models as orm
    from mission_control.work_observation.evaluate import EvaluationService
    from mission_control.work_observation.verify import claim_identity
    from mission_control.persistence.db import Database
    from mission_control.persistence.migrations import apply_migrations

    database = Database(runtime)
    apply_migrations(database)
    svc = EvaluationService(database)
    text = "All 12 tests passed"
    d1 = claim_identity(text, "ep:A", "r1")
    d2 = claim_identity(text, "ep:A", "r1")
    assert d1 == d2
    assert claim_identity(text, "ep:A", "r2") != d1
    with database.session() as session:
        session.add(orm.WoEpisode(id="ep:A", project_key="p", title="A",
                                  kind="task", status="established"))
        session.add(orm.WoClaim(id="c1", episode_id="ep:A", claimant="a",
                                text=text, scope="s", source_ref="r1"))
        session.add(orm.WoClaim(id="c2", episode_id="ep:A", claimant="a",
                                text=text, scope="s", source_ref="r1"))
        out1 = svc._store_claim_verification(
            session, "c1", "ep:A",
            __import__("mission_control.work_observation.verify",
                       fromlist=["ClaimVerification"]).ClaimVerification(
                claim_id="c1", verdict="reported_only", rationale="r",
                evidence_refs=[]),
            evaluator="deterministic", digest=d1)
        out2 = svc._store_claim_verification(
            session, "c2", "ep:A",
            __import__("mission_control.work_observation.verify",
                       fromlist=["ClaimVerification"]).ClaimVerification(
                claim_id="c2", verdict="reported_only", rationale="r",
                evidence_refs=[]),
            evaluator="deterministic", digest=d2)
    assert out1.get("cached") is None and out2.get("cached") is True
    database.dispose()


