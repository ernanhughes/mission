def test_rollup_strict_verified_only() -> None:
    from mission_control.work_observation.verify import RequirementAssessment

    def _a(rid, verdict):
        return RequirementAssessment(rid, verdict, "", [], "strong")
    assert rollup_completion([_a("a", "satisfied_verified")], {"a"})[0] == "complete"
    assert rollup_completion([_a("a", "satisfied_reported")], {"a"})[0] == "partial"
    assert rollup_completion([_a("a", "not_satisfied")], {"a"})[0] == "incomplete"
    assert rollup_completion([_a("a", "satisfied_verified")], {"a", "b"})[0] == "unknown"
    assert rollup_completion([], set())[0] == "unknown"


