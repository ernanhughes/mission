def _fake_backend_eval(payload):
    class _B:
        name = "fake-eval"

        def complete(self, _packet: str):
            return {"data": payload, "cost_usd": 0.0,
                    "tokens_in": 5, "tokens_out": 5, "latency_ms": 1}

    return _B()


