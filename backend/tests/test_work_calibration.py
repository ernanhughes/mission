"""WORK-OUTCOME-01 W9D: calibration corpus with independently set expectations.

Hand-annotated fixtures (never generated by the system under test).
Each case asserts the mechanical contract: what the engine must report
(and must refuse to report) for a given evidence state. This is the
negative-control complement to the pilot: it proves withholding, not
just recognition.
"""

from mission_control.work_observation.evaluate import EvaluationService
from mission_control.work_observation.grouping import build_groups
from mission_control.work_observation.verify import (
    EvidenceItem,
    RequirementAssessment,
    assess_requirement_deterministic,
    rollup_completion,
    verify_claim_deterministic,
)

_E = EvidenceItem


def _req(**kw):
    base = {"id": "r1", "authority": "explicit_user", "mandatory": True,
            "kind": "functional", "text": "Do the thing"}
    base.update(kw)
    return base


def _mk(i: str, v: str) -> RequirementAssessment:
    return RequirementAssessment(i, v, "r", [], "strong")


# -- requirement verdicts ------------------------------------------------

def test_cal_missing_evidence_is_insufficient_not_failure() -> None:
    a = assess_requirement_deterministic(_req(), [], False)
    assert a.verdict == "insufficient_evidence"


def test_cal_sibling_evidence_makes_missing_mandatory_not_satisfied() -> None:
    a = assess_requirement_deterministic(_req(), [], True)
    assert a.verdict == "not_satisfied"


def test_cal_existence_with_resolved_file_verifies() -> None:
    a = assess_requirement_deterministic(
        _req(kind="existence", text="Add file exists manifest"),
        [_E("file", "manifest.yaml", True)], False)
    assert a.verdict == "satisfied_verified"


def test_cal_functional_with_git_evidence_only_reports() -> None:
    a = assess_requirement_deterministic(
        _req(), [_E("git_commit", "uid:abc123", True)], False)
    assert a.verdict == "satisfied_reported"


def test_cal_ambiguous_authority_abstains_despite_evidence() -> None:
    a = assess_requirement_deterministic(
        _req(authority="ambiguous"),
        [_E("git_commit", "uid:abc123", True)], True)
    assert a.verdict == "insufficient_evidence"


def test_cal_deferred_superseded_excluded_are_terminal() -> None:
    assert assess_requirement_deterministic(
        _req(authority="deferred"), [_E("file", "x", True)],
        False).verdict == "authorized_deferral"
    assert assess_requirement_deterministic(
        _req(authority="superseded"), [], False).verdict == "superseded"
    assert assess_requirement_deterministic(
        _req(authority="excluded"), [], False).verdict == "not_applicable"


def test_cal_noncode_without_commits_is_insufficient() -> None:
    a = assess_requirement_deterministic(
        _req(kind="research", text="Investigate caching approaches"),
        [], False)
    assert a.verdict == "insufficient_evidence"


# -- claim verdicts --------------------------------------------------------

def test_cal_unresolvable_sha_claim_is_reported_not_failed() -> None:
    v = verify_claim_deterministic(
        {"id": "c", "text": "merged into main and pushed"}, [], [])
    assert v.verdict == "reported_only"


def test_cal_resolvable_sha_claim_verifies_existence() -> None:
    # NOTE: the engine passes bare SHAs (target_ref split); full
    # "uid:sha" refs never reach this function. Fixture honors that.
    v = verify_claim_deterministic(
        {"id": "c", "text": "merged commit abc1234"},
        ["abc1234def456"], [])
    assert v.verdict == "verified_commit_exists"


def test_cal_test_report_without_record_is_reported() -> None:
    v = verify_claim_deterministic(
        {"id": "c", "text": "214 tests passed"}, ["uid:abc"], [])
    assert v.verdict == "reported_only"


# -- completion rollup ------------------------------------------------------

def test_cal_complete_requires_all_mandatory_verified() -> None:
    assert rollup_completion([_mk("a", "satisfied_verified")],
                             {"a"})[0] == "complete"
    assert rollup_completion([_mk("a", "satisfied_reported")],
                             {"a"})[0] != "complete"


def test_cal_partial_reported_never_complete() -> None:
    verdict, _ = rollup_completion(
        [_mk("a", "satisfied_verified"), _mk("b", "satisfied_reported")],
        {"a", "b"})
    assert verdict == "partial"


def test_cal_contradicted_or_missing_mandatory_is_incomplete() -> None:
    assert rollup_completion([_mk("a", "contradicted")], {"a"})[0] == "incomplete"
    assert rollup_completion([_mk("a", "not_satisfied")], {"a"})[0] == "incomplete"
    assert rollup_completion([], {"a"})[0] == "unknown"


# -- findings: no false missing-work, no false completion --------------------

def _svc() -> EvaluationService:
    return EvaluationService.__new__(EvaluationService)


def test_cal_completion_claim_without_counterevidence_is_minor_gap() -> None:
    svc = _svc()
    out = svc._synthesize_findings(
        "ep:x", [], {},
        [{"claim_id": "c1", "verdict": "reported_only",
          "rationale": "commit assertion without resolvable reference",
          "evidence": []}],
        {"c1": "merged into main and pushed"},
        merged_claim_ids=frozenset())
    kinds = [(f["kind"], f["severity"]) for f in out]
    assert ("unsupported_claim", "minor") in kinds
    assert not [k for k, s in kinds if s == "major"]


def test_cal_contradicted_requirement_yields_major_defect() -> None:
    svc = _svc()
    final = {"rq": RequirementAssessment("rq", "contradicted", "r",
                                         ["e:1"], "strong")}
    out = svc._synthesize_findings(
        "ep:x", [type("R", (), {"id": "rq", "text": "t",
                                "mandatory": True})()],
        final, [], {})
    kinds = [(f["kind"], f["severity"]) for f in out]
    assert ("defect", "major") in kinds


def test_cal_identical_wording_dedupes_distinct_wordings_split() -> None:
    a = {"id": "f1", "episode_id": "e", "project_key": "p",
         "kind": "unsupported_claim", "severity": "minor",
         "status": "suspected", "title": "Same words here", "claim_text": "Same words here"}
    b = dict(a, id="f2")
    c = dict(a, id="f3", title="Different words",
             claim_text="Different words")
    groups = build_groups([a, b, c])
    assert len(groups) == 2
    assert sorted(g["member_count"] for g in groups) == [1, 2]


